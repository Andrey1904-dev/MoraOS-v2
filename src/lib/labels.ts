/** Русская подпись доменного значения. Неизвестное значение показывается как есть. */
export const label = (value?: string | null): string => {
  if (value === undefined || value === null || value === "") return "—";
  return dictionary[value] ?? value;
};

/** То же, что `label`, но для списков: переводит каждое значение. */
export const labelMany = (values: readonly string[]): string[] => values.map((v) => label(v));

